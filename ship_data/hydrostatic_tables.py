def calculate_displacement_from_cb(draught: float, trim: float, lpp: float, breadth: float) -> float:
    """
    使用方形系数计算排水量

    公式: DISP = CB × L × B × T × ρ

    Args:
        draught: 吃水 (m)
        trim: 纵倾 (m)
        lpp: 垂线间长 (m)
        breadth: 型宽 (m)

    Returns:
        float: 排水量 (t)
    """
    cb = get_cb_at_condition(draught, trim)
    rho = 1.025  # 海水密度 (t/m³)
    displacement = cb * lpp * breadth * draught * rho
    return displacement


def calculate_buoyancy_by_stations(
    draught: float,
    trim: float,
    total_displacement: float,
    lpp: float,
    n_stations: int = 21,
    use_cp_distribution: bool = True
) -> dict:
    """
    计算每两个相邻站点之间的浮力

    改进方法：
    1. 将船长分为n_stations个站点
    2. 对于每个站点，考虑纵倾影响计算局部吃水
    3. 使用CP系数构造沿船长的浮力分布形状
    4. 使用CB和局部吃水调整浮力大小
    5. 归一化使总浮力等于总排水量

    Args:
        draught: 平均吃水 (m)
        trim: 纵倾 (m)，正值表示尾倾
        total_displacement: 总排水量 (t)
        lpp: 垂线间长 (m)
        n_stations: 站点数量，默认21
        use_cp_distribution: 是否使用CP系数构造分布形状

    Returns:
        dict: 包含站点位置和浮力分布的字典
    """
    # 站点位置（从AP到FP）
    stations = np.linspace(0, lpp, n_stations)
    x_norm = stations / lpp  # 归一化位置 [0, 1]

    # 计算每个站点的局部吃水（考虑纵倾）
    lcf = lpp / 2  # 简化假设浮心在船中
    local_draughts = np.zeros(n_stations)

    for i, x in enumerate(stations):
        # 由于纵倾，局部吃水变化
        # trim > 0: 尾倾，尾部吃水增加，首部吃水减少
        draught_change = trim * (x - lcf) / lpp
        local_draughts[i] = draught + draught_change
        # 确保吃水非负
        local_draughts[i] = max(0.1, local_draughts[i])

    # 计算每个站点的系数值
    cb_values = np.zeros(n_stations)
    cp_values = np.zeros(n_stations)
    cm_values = np.zeros(n_stations)

    for i in range(n_stations):
        cb_values[i] = get_cb_at_condition(local_draughts[i], 0.0)
        cp_values[i] = get_cp_at_condition(local_draughts[i], 0.0)
        cm_values[i] = get_cm_at_condition(local_draughts[i], 0.0)

    # 使用CP系数构造浮力分布形状
    if use_cp_distribution:
        # CP系数反映了浮力沿船长的分布特征
        # CP越大，浮力分布越均匀；CP越小，浮力越集中在中部

        # 获取平均CP值
        cp_mean = np.mean(cp_values)

        # 构造形状函数（基于CP的抛物线分布）
        # 使用4次多项式来模拟真实船型
        shape_factor = np.zeros(n_stations)

        for i, x in enumerate(x_norm):
            if x < 0.15:  # 首部（0-15%）
                # 首部：指数增长
                t = x / 0.15
                shape_factor[i] = 0.2 * (1 - np.exp(-4 * t))
            elif x > 0.85:  # 尾部（85%-100%）
                # 尾部：指数衰减
                t = (1 - x) / 0.15
                shape_factor[i] = 0.2 * (1 - np.exp(-4 * t))
            else:  # 中部（15%-85%）
                # 中部：使用CP调整的多项式
                t = (x - 0.5) / 0.35  # 归一化到[-1, 1]
                # CP影响分布的平坦程度
                a = 0.6 * (1 - cp_mean)  # CP小→a大→更集中
                b = 0.4 * (1 - cp_mean)
                shape_factor[i] = 1.0 - a * t**2 - b * t**4

        # 确保非负
        shape_factor = np.maximum(shape_factor, 0.01)

        # 结合CB和局部吃水
        # 浮力 ∝ shape_factor × CB × T
        buoyancy_density = shape_factor * cb_values * local_draughts
    else:
        # 简单方法：浮力 ∝ CB × T
        buoyancy_density = cb_values * local_draughts

    # 归一化使总浮力等于总排水量
    total_buoyancy_raw = np.sum(buoyancy_density)
    if total_buoyancy_raw > 0:
        buoyancy_distribution = buoyancy_density * total_displacement / total_buoyancy_raw
    else:
        buoyancy_distribution = np.ones(n_stations) * total_displacement / n_stations

    # 计算每段之间的浮力（相邻站点的平均值）
    segment_buoyancy = np.zeros(n_stations - 1)
    segment_positions = np.zeros(n_stations - 1)

    for i in range(n_stations - 1):
        segment_buoyancy[i] = (buoyancy_distribution[i] + buoyancy_distribution[i+1]) / 2
        segment_positions[i] = (stations[i] + stations[i+1]) / 2

    return {
        'stations': stations,
        'station_buoyancy': buoyancy_distribution,
        'segment_positions': segment_positions,
        'segment_buoyancy': segment_buoyancy,
        'local_draughts': local_draughts,
        'cb_values': cb_values,
        'cp_values': cp_values,
        'cm_values': cm_values,
        'total_buoyancy': np.sum(buoyancy_distribution),
    }

